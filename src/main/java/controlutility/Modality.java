package controlutility;

/**
 * Type of modality.
 */
public enum Modality {

    /**
     * Standard mode.
     */
    STANDARD, 

    /**
     * One versus one.
     * 
     * Play against another player.
     */
    ONE_VS_ONE, 

    /**
     * Beat the Timer.
     * 
     * Finish the game before a certain time expires.
     */
    BTT;

}
